"use client"

import { useState } from "react"
import { useRouter } from "next/navigation"
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from "@/components/ui/card"
import { Button } from "@/components/ui/button"
import { Badge } from "@/components/ui/badge"
import { Tabs, TabsList, TabsTrigger } from "@/components/ui/tabs"
import { FileText, Eye, Sparkles, Loader2, X } from "lucide-react"
import { Dialog, DialogContent, DialogDescription, DialogHeader, DialogTitle } from "@/components/ui/dialog"
import { toast } from "@/hooks/use-toast"
import { authFetch } from "@/lib/auth-fetch"
import { IELTS_TOPICS, tagsIncludeTopic } from "@/lib/ielts-topics"
import { CATEGORY_GROUPS, categoriesForTask } from "@/lib/ielts-categories"
import { Task1VisualView } from "@/components/tasks/task1-visual-lazy"

type Prompt = {
  id: string
  type: "Task 1" | "Task 2"
  category?: string
  visual?: unknown // Task 1 only; validated again when rendered
  title: string
  description: string
  tags: string[]
}

const availableTopics: readonly string[] = IELTS_TOPICS

export function PromptsLibrary() {
  const router = useRouter()
  const [activeTab, setActiveTab] = useState<string>("Task 1")
  const [selectedTopics, setSelectedTopics] = useState<string[]>([])
  const [selectedCategories, setSelectedCategories] = useState<string[]>([])
  const [previewPrompt, setPreviewPrompt] = useState<Prompt | null>(null)
  const [prompts, setPrompts] = useState<Prompt[]>([])
  const [isLoading, setIsLoading] = useState(false)

  // Nothing is generated until the learner has picked what they want to practise
  const missingChoice =
    selectedTopics.length === 0 ? "topic" : selectedCategories.length === 0 ? "category" : null
  const canGenerate = missingChoice === null && !isLoading

  // Generates for the open tab, from the chosen topics and question types only
  const generatePrompts = async () => {
    if (missingChoice) return
    setIsLoading(true)
    try {
      const response = await authFetch("/api/ai/generate-prompts", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          taskType: activeTab,
          topics: selectedTopics,
          categories: selectedCategories,
          count: 6,
        }),
      })

      const result = await response.json()

      if (!response.ok) {
        // Check for rate limit errors
        if (response.status === 429 || result?.errorType === "RATE_LIMIT") {
          throw new Error(result?.error || "AI tạo đề bài đang vượt giới hạn sử dụng. Vui lòng thử lại sau vài phút.")
        } else {
          throw new Error(result?.error || "Failed to generate prompts. Please try again.")
        }
      }

      setPrompts(result.prompts)
      toast({ title: "New prompts generated!" })
    } catch (error) {
      console.error("Error generating prompts:", error)
      toast({
        title: "Lỗi",
        description: error instanceof Error ? error.message : "Failed to generate prompts. Please try again.",
        variant: "destructive",
      })
    } finally {
      setIsLoading(false)
    }
  }

  const filteredPrompts = prompts.filter((prompt) => {
    const matchesType = prompt.type === activeTab
    const matchesTopics =
      selectedTopics.length === 0 || selectedTopics.some((topic) => tagsIncludeTopic(prompt.tags, topic))
    const matchesCategory =
      selectedCategories.length === 0 || (!!prompt.category && selectedCategories.includes(prompt.category))
    return matchesType && matchesTopics && matchesCategory
  })

  const toggleTopic = (topic: string) => {
    setSelectedTopics((prev) => (prev.includes(topic) ? prev.filter((t) => t !== topic) : [...prev, topic]))
  }

  const toggleCategory = (category: string) => {
    setSelectedCategories((prev) => (prev.includes(category) ? prev.filter((c) => c !== category) : [...prev, category]))
  }

  // Switching to a task tab drops categories from the other task, so the filter can't hide everything
  const handleTabChange = (tab: string) => {
    setActiveTab(tab)
    const allowed: readonly string[] = categoriesForTask(tab)
    setSelectedCategories((prev) => prev.filter((c) => allowed.includes(c)))
  }

  const clearOptions = () => {
    setSelectedTopics([])
    setSelectedCategories([])
  }

  const visibleCategoryGroups = CATEGORY_GROUPS.filter((g) => g.task === activeTab)

  const handleUsePrompt = (prompt: Prompt) => {
    // Store the prompt in sessionStorage for use in the new task page
    sessionStorage.setItem("selectedPrompt", JSON.stringify(prompt))
    router.push(`/tasks/new`)
  }

  return (
    <div>
      <div className="mb-6">
        <h1 className="text-3xl font-bold mb-2" id="prompts-library" data-toc-title="Practice Prompts">AI-Generated Practice Prompts</h1>
        <p className="text-muted-foreground">
          Discover unique IELTS writing prompts generated by AI based on your preferences
        </p>
      </div>

      <Tabs value={activeTab} onValueChange={handleTabChange} className="mb-6" id="prompt-tabs" data-toc-title="Prompt Tabs">
        <TabsList>
          <TabsTrigger value="Task 1">Task 1</TabsTrigger>
          <TabsTrigger value="Task 2">Task 2</TabsTrigger>
        </TabsList>
      </Tabs>

      {/* Topic Selection */}
      <Card className="rounded-2xl border-border bg-card mb-6" id="topic-selection" data-toc-title="Topic Selection">
        <CardHeader>
          <div className="flex flex-wrap items-center justify-between gap-3">
            <CardTitle className="text-base">Select Topics</CardTitle>
            <div className="flex flex-wrap items-center gap-2">
            <Button
              onClick={clearOptions}
              disabled={selectedTopics.length === 0 && selectedCategories.length === 0}
              size="sm"
              variant="outline"
              className="gap-2"
            >
              <X className="h-4 w-4" />
              Clear options
            </Button>
            <Button onClick={generatePrompts} disabled={!canGenerate} size="sm" className="gap-2">
              {isLoading ? (
                <>
                  <Loader2 className="h-4 w-4 animate-spin" />
                  Generating...
                </>
              ) : (
                <>
                  <Sparkles className="h-4 w-4" />
                  Generate New Prompts
                </>
              )}
            </Button>
            </div>
          </div>
        </CardHeader>
        <CardContent>
          <div className="flex flex-wrap gap-2">
            {availableTopics.map((topic) => (
              <Badge
                key={topic}
                variant={selectedTopics.includes(topic) ? "default" : "outline"}
                className="cursor-pointer"
                onClick={() => toggleTopic(topic)}
              >
                {topic}
              </Badge>
            ))}
          </div>
          <p className="text-sm text-muted-foreground mt-3">
            {selectedTopics.length === 0
              ? "Step 1: pick at least one topic."
              : `${selectedTopics.length} topic(s) selected`}
          </p>

          <div className="mt-6 border-t border-border pt-5" id="category-selection" data-toc-title="Category Selection">
            <h3 className="text-base font-display font-semibold mb-3">Select Categories</h3>
            <div className="space-y-3">
              {visibleCategoryGroups.map((group) => (
                <div key={`${group.task}-${group.label}`} className="flex flex-col gap-2 sm:flex-row sm:items-baseline sm:gap-4">
                  <p className="shrink-0 text-sm font-medium text-muted-foreground sm:w-56">
                    {group.task} · {group.label}
                  </p>
                  <div className="flex flex-wrap gap-2">
                    {group.items.map((category) => (
                      <Badge
                        key={category}
                        variant={selectedCategories.includes(category) ? "default" : "outline"}
                        className="cursor-pointer"
                        onClick={() => toggleCategory(category)}
                      >
                        {category}
                      </Badge>
                    ))}
                  </div>
                </div>
              ))}
            </div>
            <p className="text-sm text-muted-foreground mt-3">
              {selectedCategories.length === 0
                ? "Step 2: pick at least one question type."
                : `${selectedCategories.length} categor${selectedCategories.length === 1 ? "y" : "ies"} selected`}
            </p>
          </div>
        </CardContent>
      </Card>

      {/* Loading State */}
      {isLoading && (
        <div className="flex items-center justify-center py-12">
          <div className="text-center">
            <Loader2 className="h-8 w-8 animate-spin mx-auto mb-4 text-primary" />
            <p className="text-muted-foreground">Generating unique prompts for you...</p>
          </div>
        </div>
      )}

      {/* Prompts Grid */}
      {!isLoading && filteredPrompts.length === 0 && (
        <Card className="rounded-2xl border-border bg-card">
          <CardContent className="py-12 text-center">
            <p className="text-muted-foreground mb-4">
              {missingChoice === "topic"
                ? "Pick at least one topic, then at least one question type, and press Generate."
                : missingChoice === "category"
                  ? "Now pick at least one question type, then press Generate."
                  : prompts.length === 0
                    ? "Ready. Press Generate to create prompts for your choices."
                    : "No prompts match your filters."}
            </p>
            <Button onClick={generatePrompts} disabled={!canGenerate} className="gap-2">
              <Sparkles className="h-4 w-4" />
              Generate Prompts
            </Button>
          </CardContent>
        </Card>
      )}

      {!isLoading && filteredPrompts.length > 0 && (
        <div className="stagger-children grid md:grid-cols-2 gap-6" id="prompts-grid" data-toc-title="Available Prompts">
          {filteredPrompts.map((prompt) => (
            <Card key={prompt.id} className="rounded-2xl border-border bg-card transition-colors hover:border-foreground/25">
              <CardHeader>
                <div className="flex items-start justify-between mb-2">
                  <div className="flex flex-wrap gap-2">
                    <Badge variant="outline">{prompt.type}</Badge>
                    {prompt.category && <Badge variant="secondary">{prompt.category}</Badge>}
                  </div>
                  <FileText className="h-5 w-5 text-muted-foreground" />
                </div>
                <CardTitle className="text-lg">{prompt.title}</CardTitle>
                <CardDescription className="line-clamp-2">{prompt.description}</CardDescription>
              </CardHeader>
              <CardContent>
                {prompt.visual != null && (
                  <button
                    type="button"
                    onClick={() => setPreviewPrompt(prompt)}
                    className="mb-4 block w-full rounded-md text-left focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-ring"
                    aria-label={`Preview ${prompt.title}`}
                  >
                    <Task1VisualView visual={prompt.visual} compact />
                  </button>
                )}
                <div className="flex flex-wrap gap-2 mb-4">
                  {prompt.tags.map((tag) => (
                    <Badge key={tag} variant="secondary" className="text-xs">
                      {tag}
                    </Badge>
                  ))}
                </div>
                <div className="flex gap-2">
                  <Button
                    variant="outline"
                    size="sm"
                    onClick={() => setPreviewPrompt(prompt)}
                    className="flex-1 bg-transparent"
                  >
                    <Eye className="mr-2 h-4 w-4" />
                    Preview
                  </Button>
                  <Button size="sm" onClick={() => handleUsePrompt(prompt)} className="flex-1">
                    Use this prompt
                  </Button>
                </div>
              </CardContent>
            </Card>
          ))}
        </div>
      )}

      {/* Preview Dialog */}
      <Dialog open={!!previewPrompt} onOpenChange={() => setPreviewPrompt(null)}>
        <DialogContent className="max-h-[90vh] overflow-y-auto sm:max-w-3xl">
          <DialogHeader>
            <div className="flex items-center gap-2 mb-2">
              <Badge variant="outline">{previewPrompt?.type}</Badge>
              {previewPrompt?.category && <Badge variant="secondary">{previewPrompt.category}</Badge>}
            </div>
            <DialogTitle>{previewPrompt?.title}</DialogTitle>
            <DialogDescription className="text-base leading-relaxed pt-4">
              {previewPrompt?.description}
            </DialogDescription>
          </DialogHeader>
          {previewPrompt?.visual != null && <Task1VisualView visual={previewPrompt.visual} />}
          <div className="flex gap-2 pt-4">
            <Button variant="outline" onClick={() => setPreviewPrompt(null)} className="flex-1 bg-transparent">
              Close
            </Button>
            <Button
              onClick={() => {
                if (previewPrompt) handleUsePrompt(previewPrompt)
              }}
              className="flex-1"
            >
              Use this prompt
            </Button>
          </div>
        </DialogContent>
      </Dialog>
    </div>
  )
}
